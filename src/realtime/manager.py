"""Async session manager and WebSocket broadcaster."""
from __future__ import annotations

import asyncio
import csv
import io
import uuid
from datetime import datetime, timezone
from pathlib import Path

import yaml

from .engine import RealtimeInferenceEngine
from .simulator import SoftwareBatteryPlant, forecast_plant
from .store import RealtimeStore


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


class DigitalTwinManager:
    def __init__(self, root: Path, database: Path):
        self.root = root
        with open(root / "configs/digital_twin.yaml", encoding="utf-8") as handle:
            self.config = yaml.safe_load(handle)
        self.engine = RealtimeInferenceEngine(root, self.config)
        self.store = RealtimeStore(database)
        self.session_id: str | None = None
        self.status = "idle"
        self.sequence = 0
        self.speed = float(self.config["simulation"]["default_speed"])
        self.plant: SoftwareBatteryPlant | None = None
        self.scenario_name = self.config["simulation"]["default_scenario"]
        self.current_override: float | None = None
        self.cooling_override: float | None = None
        self.last_payload: dict | None = None
        self._task: asyncio.Task | None = None
        self._subscribers: set[asyncio.Queue] = set()

    def catalog(self) -> dict:
        return {
            "scenarios": self.config["scenarios"],
            "thresholds": self.config["experimental_thresholds"],
            "model": {
                "checkpoint": self.engine.checkpoint_path.name,
                "training_mode": self.engine.summary.get("mode", "unknown"),
                "steps_completed": self.engine.summary.get("steps_completed"),
                "validation_metrics": self.engine.summary.get("metrics", {}),
            },
            "disclaimers": [
                "All telemetry is generated by a software battery plant; no hardware is connected.",
                "Temperature is a lumped cell value, not a spatial hotspot coordinate.",
                "Thresholds are configurable experimental limits, not certified BMS limits.",
            ],
        }

    async def start(self, scenario: str, speed: float = 5.0) -> dict:
        if scenario not in self.config["scenarios"]:
            raise ValueError(f"Unknown scenario: {scenario}")
        await self.stop()
        self.session_id = uuid.uuid4().hex[:12]
        self.scenario_name = scenario
        self.speed = min(20.0, max(0.5, float(speed)))
        self.sequence = 0
        self.current_override = None
        self.cooling_override = None
        self.plant = SoftwareBatteryPlant(self.config["simulation"], scenario, self.config["scenarios"][scenario])
        self.status = "running"
        self.store.start_session(self.session_id, scenario, utc_now(), {"speed": self.speed, "source": "software_simulator"})
        self._task = asyncio.create_task(self._run())
        return self.state()

    async def stop(self) -> None:
        if self._task and not self._task.done():
            self._task.cancel()
            try: await self._task
            except asyncio.CancelledError: pass
        if self.session_id and self.status not in {"idle", "complete"}:
            self.store.set_status(self.session_id, "stopped", utc_now())
        self._task = None
        self.status = "idle"

    async def pause(self) -> dict:
        if self.status == "running":
            self.status = "paused"
            self.store.set_status(self.session_id, "paused")
        return self.state()

    async def resume(self) -> dict:
        if self.status == "paused":
            self.status = "running"
            self.store.set_status(self.session_id, "running")
        return self.state()

    def control(self, speed: float | None = None, c_rate: float | None = None, cooling: float | None = None) -> dict:
        if speed is not None: self.speed = min(20.0, max(0.5, float(speed)))
        self.current_override = None if c_rate is None else min(2.5, max(0.1, float(c_rate)))
        self.cooling_override = None if cooling is None else min(2.0, max(0.0, float(cooling)))
        return self.state()

    def state(self) -> dict:
        return {"status": self.status, "session_id": self.session_id, "scenario": self.scenario_name, "speed": self.speed, "sequence": self.sequence, "last_payload": self.last_payload}

    async def subscribe(self) -> asyncio.Queue:
        queue: asyncio.Queue = asyncio.Queue(maxsize=4)
        self._subscribers.add(queue)
        if self.last_payload: await queue.put(self.last_payload)
        return queue

    def unsubscribe(self, queue: asyncio.Queue) -> None:
        self._subscribers.discard(queue)

    async def _broadcast(self, payload: dict) -> None:
        for queue in list(self._subscribers):
            if queue.full():
                try: queue.get_nowait()
                except asyncio.QueueEmpty: pass
            await queue.put(payload)

    async def _run(self) -> None:
        interval = float(self.config["simulation"]["tick_interval_s"])
        base_step = float(self.config["simulation"]["simulated_step_s"])
        while self.plant and self.plant.soc > 0.03:
            if self.status == "paused":
                await asyncio.sleep(0.15)
                continue
            telemetry = self.plant.step(base_step * self.speed, self.current_override, self.cooling_override)
            prediction = self.engine.predict(self.plant.time_s, telemetry["c_rate"], telemetry["ambient_C"])
            forecasts = self._forecasts(telemetry)
            risk = self._risk(telemetry, prediction, forecasts)
            self.sequence += 1
            payload = {
                "type": "telemetry", "source": "software_simulator", "session_id": self.session_id,
                "sequence": self.sequence, "wall_time": utc_now(), "simulated_time_s": round(self.plant.time_s, 3),
                "scenario": self.scenario_name, "telemetry": telemetry, "prediction": prediction,
                "forecasts": forecasts, "risk": risk,
            }
            self.last_payload = payload
            self.store.save_tick(payload)
            await self._broadcast(payload)
            await asyncio.sleep(interval)
        if self.session_id:
            self.status = "complete"
            self.store.set_status(self.session_id, "complete", utc_now())
            await self._broadcast({"type": "session_complete", "session_id": self.session_id})

    def _forecasts(self, telemetry: dict) -> list[dict]:
        scenario = self.config["scenarios"][self.scenario_name]
        forecasts = []
        for seconds in (30.0, 60.0, 300.0):
            future = self.engine.predict(self.plant.time_s + seconds, telemetry["c_rate"], telemetry["ambient_C"])
            measured_forecast = forecast_plant(telemetry, self.config["simulation"], seconds, telemetry["c_rate"], telemetry["cooling_factor"], float(scenario.get("extra_heat_W", 0.0)))
            forecasts.append({"horizon_s": seconds, "pinn_temperature_C": round(future["temperature_C"], 3), "hybrid_temperature_C": measured_forecast, "peak_stress_MPa": round(future["peak_tensile_stress_MPa"], 3)})
        return forecasts

    def compare(self, horizon_s: float = 300.0) -> list[dict]:
        if not self.last_payload: raise ValueError("Start a session before comparing interventions")
        t = self.last_payload["telemetry"]
        baseline_c, baseline_cooling = t["c_rate"], t["cooling_factor"]
        options = [("Continue current load", baseline_c, baseline_cooling), ("Reduce load by 40%", max(0.25, baseline_c * 0.6), baseline_cooling), ("Enhance cooling", baseline_c, min(2.0, baseline_cooling * 1.8))]
        return [{"action": label, "c_rate": round(c_rate, 3), "cooling_factor": round(cooling, 3), "temperature_C": forecast_plant(t, self.config["simulation"], horizon_s, c_rate, cooling), "basis": "hybrid experimental forecast"} for label, c_rate, cooling in options]

    def _risk(self, telemetry: dict, prediction: dict, forecasts: list[dict]) -> dict:
        limits = self.config["experimental_thresholds"]
        peak_temp = max([telemetry["surface_temperature_C"], prediction["temperature_C"]] + [item["hybrid_temperature_C"] for item in forecasts])
        stress = abs(prediction["peak_tensile_stress_MPa"])
        reasons = []
        level = "normal"
        if peak_temp >= limits["temperature_critical_C"] or stress >= limits["tensile_stress_critical_MPa"]:
            level = "critical"; reasons.append("An experimental critical threshold is exceeded")
        elif peak_temp >= limits["temperature_warning_C"] or stress >= limits["tensile_stress_warning_MPa"]:
            level = "warning"; reasons.append("An experimental warning threshold is exceeded")
        if prediction["confidence"] < limits["model_confidence_warning"]:
            if level == "normal": level = "caution"
            reasons.extend(prediction["domain_reasons"] or ["Model confidence is below the configured threshold"])
        if telemetry["soc_percent"] <= limits["soc_low_percent"]:
            if level == "normal": level = "caution"
            reasons.append("State of charge is below the experimental low-SOC threshold")
        recommendation = {"normal":"Continue monitoring","caution":"Review model domain and operating condition","warning":"Reduce load or increase cooling in the simulated scenario","critical":"Stop the simulated discharge and inspect the event"}[level]
        return {"level": level, "reasons": reasons, "recommendation": recommendation, "threshold_type": "experimental"}

    def export_csv(self, session_id: str) -> str:
        rows = self.store.session_rows(session_id)
        if not rows: raise ValueError("Session not found or contains no telemetry")
        stream = io.StringIO()
        writer = csv.DictWriter(stream, fieldnames=[key for key in rows[0] if key != "payload_json"])
        writer.writeheader(); writer.writerows([{k:v for k,v in row.items() if k != "payload_json"} for row in rows])
        return stream.getvalue()
